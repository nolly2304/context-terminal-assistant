"""Generate docs/analysis/usage-patterns.md from the datasets in data/raw/.

Usage:  cta-analyse [--data data] [--out docs/analysis/usage-patterns.md] [--own PATH]

Only aggregate statistics are written, never individual users' command lines,
so the output is safe to commit.
"""

from __future__ import annotations

import argparse
import statistics
import time
from collections import Counter
from collections.abc import Callable
from pathlib import Path

from cta.analysis import patterns as P
from cta.analysis import predictors as R
from cta.datasets import kypo, schonlau, shell_history
from cta.datasets.model import History


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--data", default="data", type=Path)
    ap.add_argument("--out", default="docs/analysis/usage-patterns.md", type=Path)
    ap.add_argument("--own", type=Path, help="your own zsh/bash history file (optional)")
    args = ap.parse_args(argv)

    started = time.time()
    raw = args.data / "raw"
    out: list[str] = []
    w = out.append

    w("# Usage-pattern analysis (Task 3, objective P1)\n")
    w("_Generated by `cta-analyse`. Do not edit by hand; rerun the script instead._\n")
    w("All rates are means across users with 95% confidence intervals. Predictors are run "
      "online: each prediction uses only commands the user had already typed.\n")

    datasets: list[tuple[str, list[History]]] = []
    if (raw / "schonlau" / "mask.dat").exists():
        datasets.append(("Schonlau", schonlau.load(raw / "schonlau")))
    k = []
    if (raw / "svabensky").exists():
        k += kypo.load(raw / "svabensky", "svabensky")
    if (raw / "oslejsek").exists():
        k += kypo.load(raw / "oslejsek", "oslejsek")
    if k:
        datasets.append(("KYPO", k))
    if args.own:
        datasets.append(("Own history", [shell_history.load(args.own)]))

    _datasets_table(w, datasets)
    for name, histories in datasets:
        if name == "Schonlau":
            _schonlau(w, histories)
        else:
            _full_lines(w, name, histories)

    w("\nWhat these results mean for the design is discussed in "
      "[requirements.md](../requirements.md) and [decisions.md](../decisions.md). "
      "How each measure is calculated: [method.md](method.md).\n")
    w(f"\n---\n_Run time: {time.time() - started:.0f} s._\n")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {args.out}")


def _datasets_table(w, datasets: list[tuple[str, list[History]]]) -> None:
    w("## 1. Datasets\n")
    w("| Dataset | Users | Commands | Median per user | Context recorded |")
    w("|---|---|---|---|---|")
    for name, hs in datasets:
        sizes = [len(h) for h in hs]
        ctx = [a for a in ("cwd", "timestamp", "host") if any(h.has(a) for h in hs)]
        w(f"| {name} | {len(hs)} | {sum(sizes):,} | {statistics.median(sizes):,.0f} | "
          f"{', '.join(ctx) or 'program name only'} |")
    w("")


def _accuracy_table(w, histories: list[History], makers: list[Callable[[], R.Predictor]]
                    ) -> dict[str, list[float]]:
    w("| Predictor | Top-1 | Top-3 |")
    w("|---|---|---|")
    top1: dict[str, list[float]] = {}
    for make in makers:
        name = make().name
        acc = [P.top_k_accuracy(h, make) for h in histories]
        top1[name] = [a[1] for a in acc]
        w(f"| {name} | {P.summarise(top1[name])} | {P.summarise([a[3] for a in acc])} |")
    w("")
    return top1


def _schonlau(w, hs: list[History]) -> None:
    key = R.by_program
    w("## 2. Schonlau: long-term use, program names only\n")
    w("Collected with process accounting over months, so it shows long-term habits but has "
      "no arguments, and includes programs started by scripts as well as typed ones. "
      "Blocks containing another user's commands were removed.\n")
    w(f"- **Recurrence rate** (program repeats an earlier one): "
      f"{P.summarise([P.recurrence_rate(h, key) for h in hs])}")
    w(f"- **Distinct programs per user:** median "
      f"{statistics.median(P.vocabulary(h, key) for h in hs):.0f}")
    mru = [P.mru_coverage(h, key) for h in hs]
    w("- **Found among the last k distinct programs:** " + ", ".join(
        f"k={k}: {P.summarise([m[k - 1] for m in mru])}" for k in (1, 3, 5, 10)))
    w("\n**Next-program prediction**\n")
    top1 = _accuracy_table(w, hs, [
        lambda: R.MostRecent(key), lambda: R.MostFrequent(key), lambda: R.Frecency(key),
        lambda: R.Markov(key, 1), lambda: R.Markov(key, 2)])
    w("Paired difference in top-1, Markov-1 minus frecency: "
      f"{P.paired_difference(top1['markov-1'], top1['frecency']).points()}.\n")
    w("_Caution:_ process accounting also logs chains of programs launched by scripts "
      "(for example `sh` starting `cpp`), which are almost perfectly predictable. The "
      "sequence models' accuracy here is therefore an upper bound for typed commands.\n")


def _full_lines(w, name: str, hs: list[History]) -> None:
    w(f"## {'3' if name == 'KYPO' else '4'}. {name}: full command lines with context\n")
    if name == "KYPO":
        w("Bash commands from hands-on cybersecurity training in the KYPO Cyber Range "
          "(Švábenský et al., 2021; Ošlejšek et al., 2023). Each trainee is one short, "
          "task-driven session on a prepared network, so this is closest to a new user on "
          "an unfamiliar Linux server, and furthest from a developer's long-term habits.\n")

    w("**Repetition**\n")
    w("| Unit | Recurrence rate | Median distinct per user |")
    w("|---|---|---|")
    for label, key in (("Full line", R.by_line), ("Program", R.by_program)):
        w(f"| {label} | {P.summarise([P.recurrence_rate(h, key) for h in hs])} | "
          f"{statistics.median(P.vocabulary(h, key) for h in hs):.0f} |")
    w("")

    programs = Counter(e.program for h in hs for e in h)
    total = sum(programs.values())
    w("**Most used programs:** " + ", ".join(
        f"`{p}` {c / total:.0%}" for p, c in programs.most_common(10)) + "\n")

    if any(h.has("cwd") for h in hs):
        dirs = [len({e.cwd for e in h if e.cwd}) for h in hs if h.has("cwd")]
        hosts = [len({e.host for e in h if e.host}) for h in hs if h.has("host")]
        w(f"**Context variety per user:** median {statistics.median(dirs):.0f} distinct working "
          f"directories (max {max(dirs)}), median {statistics.median(hosts):.0f} host(s) "
          f"(max {max(hosts)}).\n")

    w("**Next-command prediction (full line)**\n")
    makers = [R.MostRecent, R.MostFrequent, R.Frecency, lambda: R.Markov(order=1)]
    if any(h.has("cwd") for h in hs):
        makers.append(lambda: R.ContextFrequency("cwd"))
    if any(h.has("host") for h in hs):
        makers.append(lambda: R.ContextFrequency("host"))
    top1 = _accuracy_table(w, hs, makers)
    if "context:cwd" in top1:
        w("Paired difference in top-1, directory-aware minus frecency: "
          f"{P.paired_difference(top1['context:cwd'], top1['frecency']).points()}.\n")
        w("_Note:_ here the directory-aware predictor only falls back to the user's overall "
          "habits when a directory is new. With short histories, splitting them by directory "
          "can leave too little data per directory, so context may be better used to "
          "re-weight suggestions than to filter them.\n")

    w("**Keystrokes saved by inline suggestions** (accepting a suggestion costs one key)\n")
    w("| Predictor | Whole-line suggestions | + word-by-word completion |")
    w("|---|---|---|")
    line_ks: list[float] = []
    word_ks: list[float] = []
    for make in (R.Frecency, lambda: R.Markov(order=1)):
        a = [P.keystroke_savings(h, make) for h in hs]
        b = [P.keystroke_savings(h, make, word_completion=True) for h in hs]
        if not line_ks:
            line_ks, word_ks = a, b
        w(f"| {make().name} | {P.summarise(a)} | {P.summarise(b)} |")
    w("")
    w("Paired gain from word-by-word completion (frecency): "
      f"{P.paired_difference(word_ks, line_ks).points()}.\n")


if __name__ == "__main__":
    main()
